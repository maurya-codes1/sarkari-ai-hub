    # 15 Long Answer
    for i in range(15):
        sub_count += 1
        ch_title = chapters[(i + 6) % len(chapters)]
        diff = diff_cycle[i % 3]
        all_questions.append(make_subjective(subj, sub_count, ch_title, "long_answer", 5, diff))

